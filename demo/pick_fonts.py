#!/usr/bin/env python3
"""Regenerate demo/fonts.txt: the most popular open-licensed Google Fonts families.

Takes families from github.com/google/fonts under ofl/ (SIL Open Font License),
apache/ (Apache 2.0) and ufl/ (Ubuntu Font Licence), in Google Fonts popularity
order, skipping very large families (mostly CJK), until a size budget is reached.
The families already listed in fonts.txt are always kept.

Usage: python demo/pick_fonts.py [budget-MB]   (default 200)
Set GITHUB_TOKEN to avoid the anonymous API limit.
"""
import json
import os
import re
import sys
import urllib.request

try:  # use the OS certificate store when available (helps behind HTTPS-inspecting proxies)
    import truststore
    truststore.inject_into_ssl()
except ImportError:
    pass
from collections import Counter
from pathlib import Path

LIST = Path(__file__).with_name("fonts.txt")
LICENSES = ("ofl", "apache", "ufl")
MAX_FAMILY = 2_500_000  # bytes; bigger families are skipped


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "typestash-demo-builder"})
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def main(budget_mb):
    tree = json.loads(get("https://api.github.com/repos/google/fonts/git/trees/main?recursive=1"))["tree"]
    size = Counter()
    for e in tree:
        parts = e["path"].split("/")
        if e["type"] == "blob" and len(parts) == 3 and parts[0] in LICENSES and parts[2].lower().endswith((".ttf", ".otf")):
            size[f"{parts[0]}/{parts[1]}"] += e["size"]
    by_key = {folder.split("/")[1]: folder for folder in size}

    meta = json.loads(get("https://fonts.google.com/metadata/fonts"))["familyMetadataList"]
    meta.sort(key=lambda f: f["popularity"])

    keep = [l.strip() for l in LIST.read_text().splitlines() if l.strip() and not l.startswith("#")]
    pick = [f for f in keep if f in size]
    total = sum(size[f] for f in pick)
    for fam in meta:
        folder = by_key.get(re.sub(r"[^a-z0-9]", "", fam["family"].lower()))
        if not folder or folder in pick or size[folder] > MAX_FAMILY:
            continue
        if total + size[folder] > budget_mb * 1e6:
            break
        pick.append(folder)
        total += size[folder]

    lic = Counter(f.split("/")[0] for f in pick)
    LIST.write_text(
        "# Font families for the public demo, as folders in github.com/google/fonts.\n"
        "# Generated by demo/pick_fonts.py: the most popular open-licensed families\n"
        f"# ({', '.join(f'{n} {k}' for k, n in lic.most_common())}; ofl = SIL Open Font License,\n"
        "# apache = Apache 2.0, ufl = Ubuntu Font Licence). Every .ttf/.otf in a folder is used.\n"
        + "\n".join(pick) + "\n",
        encoding="utf-8",
    )
    print(f"{len(pick)} families, {total / 1e6:.0f} MB of fonts -> {LIST}")


if __name__ == "__main__":
    main(float(sys.argv[1]) if len(sys.argv) > 1 else 200)
